import { mkdirSync } from 'node:fs'
import { join } from 'node:path'
import log from '../helpers/logger'
import { getMappingByMatrixId } from '../helpers/storage'
import { ensureStoreDir, getStorePassphrase } from './config'
import { enc, matrixRequest } from './matrix'
import { CryptoSdk, RequestTypes, loadSdk } from './sdk'

type OutgoingRequest =
  | CryptoSdk.KeysUploadRequest
  | CryptoSdk.KeysQueryRequest
  | CryptoSdk.KeysClaimRequest
  | CryptoSdk.ToDeviceRequest
  | CryptoSdk.SignatureUploadRequest
  | CryptoSdk.RoomMessageRequest
  | CryptoSdk.KeysBackupRequest

/**
 * The cryptographic identity of a migrated user during the migration: the
 * Matrix device created when the user was registered, and the OlmMachine
 * (crypto engine) holding the private keys of that device.
 */
export class CryptoSession {
  private queue: Promise<unknown> = Promise.resolve()

  constructor(
    readonly userId: string,
    readonly deviceId: string,
    readonly accessToken: string,
    readonly machine: CryptoSdk.OlmMachine
  ) {}

  /**
   * Run crypto operations of this user one after the other. The crypto
   * engine must not process concurrent key claims or room key shares.
   * @param fn The operation to run
   * @returns The result of the operation
   */
  exclusive<T>(fn: () => Promise<T>): Promise<T> {
    const result = this.queue.then(fn, fn)
    this.queue = result.catch(() => undefined)
    return result
  }

  /**
   * Send a request as this user and device
   * @param method The HTTP method
   * @param path The Client-Server API path
   * @param data The JSON body
   * @param params The query string parameters
   * @returns The JSON response
   */
  request<T = Record<string, unknown>>(
    method: 'GET' | 'POST' | 'PUT' | 'DELETE',
    path: string,
    data?: unknown,
    params?: Record<string, string | number>
  ): Promise<T> {
    return matrixRequest<T>(this.accessToken, method, path, data, params)
  }

  /**
   * Send one request generated by the crypto engine and report the
   * response back to it.
   * @param request The outgoing request
   * @returns The server's response
   */
  async sendOutgoingRequest(
    request: OutgoingRequest
  ): Promise<Record<string, unknown>> {
    const body = JSON.parse(request.body)
    let response: Record<string, unknown>

    switch (request.type as number) {
      case RequestTypes.KeysUpload:
        response = await this.request(
          'POST',
          '/_matrix/client/v3/keys/upload',
          body
        )
        break
      case RequestTypes.KeysQuery:
        response = await this.request(
          'POST',
          '/_matrix/client/v3/keys/query',
          body
        )
        break
      case RequestTypes.KeysClaim:
        response = await this.request(
          'POST',
          '/_matrix/client/v3/keys/claim',
          body
        )
        break
      case RequestTypes.SignatureUpload:
        // The crypto engine wraps the signatures in `signed_keys`, while the
        // endpoint expects them as the request body itself.
        response = await this.request(
          'POST',
          '/_matrix/client/v3/keys/signatures/upload',
          body.signed_keys ?? body
        )
        // Rejected signatures are reported inside a successful response
        if (
          response.failures &&
          Object.keys(response.failures as object).length > 0
        ) {
          throw new Error(
            `E2EE: signatures rejected for ${this.userId}: ${JSON.stringify(response.failures)}`
          )
        }
        break
      case RequestTypes.ToDevice: {
        const toDevice = request as CryptoSdk.ToDeviceRequest
        response = await this.request(
          'PUT',
          `/_matrix/client/v3/sendToDevice/${enc(toDevice.eventType)}/${enc(toDevice.txnId)}`,
          body
        )
        break
      }
      case RequestTypes.RoomMessage: {
        const message = request as CryptoSdk.RoomMessageRequest
        response = await this.request(
          'PUT',
          `/_matrix/client/v3/rooms/${enc(message.roomId)}/send/${enc(message.eventType)}/${enc(message.txnId)}`,
          body
        )
        break
      }
      default:
        throw new Error(
          `E2EE: unexpected crypto request of type ${request.type} for ${this.userId}`
        )
    }

    await this.machine.markRequestAsSent(
      request.id,
      request.type,
      JSON.stringify(response)
    )
    return response
  }

  /**
   * Send every request the crypto engine is waiting for (key uploads, key
   * queries, ...), until there are none left.
   */
  async processOutgoingRequests(): Promise<void> {
    for (let round = 0; round < 10; round++) {
      const requests = await this.machine.outgoingRequests()
      if (requests.length === 0) {
        return
      }
      for (const request of requests) {
        await this.sendOutgoingRequest(request)
      }
    }
    log.warn(`E2EE: ${this.userId} still has pending crypto requests`)
  }

  /**
   * Encrypt an event for a room with this user's device.
   *
   * The Megolm session of the room is created (or rotated) when needed. Its
   * key is only shared with the user's own other devices, if any: the other
   * room members receive it through their key backups at the end of the
   * migration.
   * @param roomId The Matrix room ID
   * @param eventType The type of the event to encrypt, e.g. m.room.message
   * @param content The plaintext event content
   * @returns The content of the m.room.encrypted event to send
   */
  encrypt(
    roomId: string,
    eventType: string,
    content: Record<string, unknown>
  ): Promise<Record<string, unknown>> {
    return this.exclusive(async () => {
      const sdk = loadSdk()
      const user = new sdk.UserId(this.userId)
      const room = new sdk.RoomId(roomId)

      const claim = await this.machine.getMissingSessions([user])
      if (claim) {
        await this.sendOutgoingRequest(claim)
      }

      for (const request of await this.machine.shareRoomKey(
        room,
        [user],
        encryptionSettings()
      )) {
        await this.sendOutgoingRequest(request)
      }

      const encrypted = JSON.parse(
        await this.machine.encryptRoomEvent(
          room,
          eventType,
          JSON.stringify(content)
        )
      ) as Record<string, unknown>

      if (
        encrypted.algorithm !== 'm.megolm.v1.aes-sha2' ||
        typeof encrypted.ciphertext !== 'string' ||
        typeof encrypted.session_id !== 'string' ||
        'body' in encrypted
      ) {
        throw new Error(
          `E2EE: invalid encryption result for ${this.userId} in ${roomId}`
        )
      }
      // Relations (threads, reactions) stay readable by the server, as the
      // Matrix specification requires for encrypted events.
      if (content['m.relates_to'] && !encrypted['m.relates_to']) {
        encrypted['m.relates_to'] = content['m.relates_to']
      }
      return encrypted
    })
  }
}

/**
 * @returns The Megolm session settings used for the migrated history
 */
function encryptionSettings(): CryptoSdk.EncryptionSettings {
  const settings = new (loadSdk().EncryptionSettings)()
  const rotation = Number(process.env.E2EE_ROTATION_MESSAGES || 1000)
  if (Number.isInteger(rotation) && rotation > 0) {
    settings.rotationPeriodMessages = BigInt(rotation)
  }
  return settings
}

const sessions = new Map<string, Promise<CryptoSession>>()

/**
 * One crypto store per user and device: a store holds exactly one Olm account
 * @param userId A Matrix user ID
 * @param deviceId The ID of the migration device
 * @returns The crypto store directory
 */
function storePathFor(userId: string, deviceId: string): string {
  const safe = (value: string) => value.replace(/[^A-Za-z0-9._=@:-]/g, '_')
  const path = join(ensureStoreDir(), safe(userId), safe(deviceId))
  mkdirSync(path, { recursive: true, mode: 0o700 })
  return path
}

/**
 * Open the crypto engine of a migrated user, publishing the device keys on
 * first use.
 * @param userId The Matrix user ID
 * @returns The user's crypto session
 */
async function openSession(userId: string): Promise<CryptoSession> {
  const mapping = await getMappingByMatrixId(userId)
  if (!mapping?.accessToken) {
    throw new Error(`E2EE: no access token found for ${userId}`)
  }

  const whoami = await matrixRequest<{ user_id: string; device_id?: string }>(
    mapping.accessToken,
    'GET',
    '/_matrix/client/v3/account/whoami'
  )
  if (whoami.user_id !== userId || !whoami.device_id) {
    throw new Error(
      `E2EE: the access token of ${userId} does not belong to a device of this user`
    )
  }

  const sdk = loadSdk()
  const machine = await sdk.OlmMachine.initialize(
    new sdk.UserId(userId),
    new sdk.DeviceId(whoami.device_id),
    storePathFor(userId, whoami.device_id),
    getStorePassphrase()
  )
  const session = new CryptoSession(
    userId,
    whoami.device_id,
    mapping.accessToken,
    machine
  )

  await session.exclusive(async () => {
    await machine.receiveSyncChanges('[]', new sdk.DeviceLists(), {}, [])
    await machine.updateTrackedUsers([new sdk.UserId(userId)])
    await session.processOutgoingRequests()
  })
  log.debug(`E2EE: crypto device ${whoami.device_id} ready for ${userId}`)
  return session
}

/**
 * Get (and open on first use) the crypto session of a migrated user
 * @param userId The Matrix user ID
 * @returns The crypto session
 */
export function getCryptoSession(userId: string): Promise<CryptoSession> {
  let session = sessions.get(userId)
  if (!session) {
    session = openSession(userId)
    sessions.set(userId, session)
    session.catch(() => sessions.delete(userId))
  }
  return session
}

/**
 * Close every crypto engine. Must be called before the process exits.
 */
export async function closeAllCryptoSessions(): Promise<void> {
  const opened = [...sessions.values()]
  sessions.clear()
  for (const pending of opened) {
    try {
      const session = await pending
      await session.exclusive(async () => session.machine.close())
    } catch {
      // the session could not be opened, nothing to close
    }
  }
}
